  // Головна функція: поза бійця для анімації в момент часу
  function poseFor(anim, t, clk, out, ex) {
    out = out || mkPose();
    const br = Math.sin(clk * 3.2);
    switch (anim) {
      case 'idle': {
        lerpPose(TLX.p[0][1], TLX.p[0][1], 0, out);
        out.hr[1] += Math.sin(clk * 1.3) * 3; out.hip[0] += Math.sin(clk * 1.3) * 0.012;
        out.hip[1] += br * 0.012; out.lh[1] += br * 0.012; out.rh[1] += br * 0.012; out.lh[2] += Math.sin(clk * 1.7) * 0.02; out.rh[2] += Math.cos(clk * 1.9) * 0.015;
        out.ch[0] += br * 1.2;
        return out;
      }
      case 'walkF': case 'walkB': {
        lerpPose(TLX.p[0][1], TLX.p[0][1], 0, out);
        // стопи стоять на землі, поки тіло рухається (без ковзання)
        const d = (ex && ex.walkD !== undefined ? ex.walkD : t * (anim === 'walkB' ? -1.8 : 2)) / 0.8;
        const stepFoot = (ph, foot) => {
          const u = ((ph % 1) + 1) % 1, L = 0.8 * 0.5;
          if (u < 0.55) { foot[2] += L / 2 - (u / 0.55) * L; }
          else { const v = (u - 0.55) / 0.45, sv = v * v * (3 - 2 * v); foot[2] += -L / 2 + sv * L; foot[1] = Math.sin(Math.PI * v) * 0.075; }
        };
        stepFoot(d, out.lf); stepFoot(d + 0.5, out.rf);
        const ph = d * TAU;
        out.hip[1] += -Math.abs(Math.sin(ph)) * 0.022; out.hip[0] += Math.sin(ph) * 0.02;
        out.hr[1] += Math.sin(ph) * 5; out.ch[1] -= Math.sin(ph) * 3;
        out.lh[1] += Math.sin(ph) * 0.012; out.rh[1] -= Math.sin(ph) * 0.012;
        out.ch[0] += anim === 'walkF' ? 4 : -2;
        return out;
      }
      case 'rush': {
        if (t < 0.25) return sampleTL('dash', t * 0.8, out);
        if (t > 1.62) return lerpPose(TLX.h[TLX.h.length - 2][1], STANCE, sstep(clamp((t - 1.62) / 0.18, 0, 1)), out);
        const n = Math.min(4, Math.floor((t - 0.25) / 0.27)), u = ((t - 0.25) - n * 0.27) / 0.27;
        const ext = u < 0.35 ? sstep(u / 0.35) : 1 - sstep((u - 0.35) / 0.65) * 0.8;
        const base = mkPose({ hip: [0, -0.12, 0.06], ch: [16, 0, 0] });
        if (n === 4) {
          // фінальний аперкот
          const up = mkPose({ rh: [0, 1.95, 0.55], re: [-0.4, -1, 0.2], hr: [-6, 26, 0], ch: [-10, 22, 0], hip: [0, 0.04, 0.1], lh: [0.2, 1.3, 0.1], lift: 0.12, rf: [-0.13, 0.1, -0.2] });
          const cr = mkPose({ rh: [-0.1, 1.0, 0.25], hip: [0, -0.28, 0.05], ch: [24, -18, 0], hr: [6, -20, 0] });
          return u < 0.3 ? lerpPose(cr, up, sstep(u / 0.3), out) : lerpPose(up, up, 0, out);
        }
        const left = n % 2 === 0;
        const hit = mkPose(left ? { lh: [0.04, 1.42, 0.84], le: [0.3, -0.3, 0], hr: [6, -40, 0], ch: [14, -24, 0], hip: [0, -0.1, 0.1] } : { rh: [0, 1.42, 0.84], re: [-0.3, -0.3, 0], hr: [6, 14, 0], ch: [14, 18, 0], hip: [0, -0.1, 0.1] });
        return lerpPose(base, hit, ext, out);
      }
      default:
        if (TLX[anim]) return sampleTL(anim, t, out);
        return lerpPose(TLX.p[0][1], TLX.p[0][1], 0, out);
    }
  }
